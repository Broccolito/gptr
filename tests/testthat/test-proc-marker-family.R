test_that("canonical markers enumerate an owned family and preserve unrelated processes", {
  skip_on_cran()
  withr::local_seed(68017)
  before_env = Sys.getenv()
  before_options = options()
  before_wd = getwd()
  seed_present = exists(".Random.seed", envir = globalenv(), inherits = FALSE)
  before_seed = if (seed_present) get(".Random.seed", envir = globalenv()) else NULL
  x = pmf_run()
  # Evaluate restoration before a failing assertion can initialize a formatter dependency.
  parent_env_restored = identical(Sys.getenv(), before_env)
  parent_options_restored = identical(options(), before_options)
  parent_wd_restored = identical(getwd(), before_wd)
  after_seed_present = exists(".Random.seed", envir = globalenv(), inherits = FALSE)
  parent_seed_restored = identical(seed_present, after_seed_present) &&
    (!seed_present || identical(before_seed, get(".Random.seed", envir = globalenv())))
  expect_true(parent_env_restored)
  expect_true(parent_options_restored)
  expect_true(parent_wd_restored)
  expect_true(parent_seed_restored)
  expect_true(x$owned_family_stopped)
  expect_identical(x$sampling_errors, 0L)
  expect_gte(x$samples, 1L)
  expect_lte(x$peak_rss, x$rss_cap)
  expect_lte(x$peak_disk, x$output_cap)
  expect_lte(x$elapsed, 60)
  expect_true(x$complete, label = paste(x$guard, paste(x$phases, collapse = "/")))
  if (!x$complete) return(invisible(NULL))
  r = x$result
  expect_true(proc_marker_valid(r$marker))
  expect_gte(length(r$owned), 2L)
  expect_gte(length(r$foreign), 1L)
  expect_true(all(vapply(c(r$owned, r$foreign), function(z) {
    proc_pid_valid(z$pid) && is.finite(z$create_time)
  }, logical(1))))
  expect_true(r$target$pid %in% vapply(r$owned, function(z) z$pid, integer(1)))
  expect_true(r$descendant$pid %in% vapply(r$owned, function(z) z$pid, integer(1)))
  expect_true(r$sentinel$pid %in% vapply(r$foreign, function(z) z$pid, integer(1)))
  expect_true(r$owned_env_exact)
  expect_true(r$foreign_env_clear)
  expect_true(r$parent_marker_absent)
  expect_true(r$raw_match)
  expect_true(r$proc_match)
  expect_true(r$rejects_missing)
  expect_true(r$rejects_extra)
  expect_true(r$rejects_substitution)
  expect_false(r$proc_unavailable)
  expect_true(r$foreign_excluded)
  expect_true(r$record_parent_alive)
  expect_true(r$identities_live)
  expect_true(r$identity_mismatch_refused)
  expect_true(r$killed)
  expect_true(r$owned_dead)
  expect_true(r$foreign_live_after_owned_kill)
  expect_true(r$foreign_unchanged)
  expect_true(r$marker_removed)
  expect_true(r$independent_cleanup)
  expect_length(r$cleanup_errors, 0L)
  expect_true(r$seed_unchanged)
  expect_true(r$env_unchanged)
  expect_true(r$wd_unchanged)
  expect_length(r$proc_warnings, 0L)
  # P04 deliberately suppresses the known legacy-format coercion warning in proc_tree().
  # Bound this raw dependency diagnostic without treating it as a missed-descendant witness.
  expect_true(length(r$raw_warnings) %in% 0:1)
  expect_true(all(vapply(r$raw_warnings, function(warning) {
    is.list(warning) && identical(names(warning), c("class", "call_head")) &&
      identical(warning$class, c("simpleWarning", "warning", "condition")) &&
      identical(warning$call_head, "ps_find_tree")
  }, logical(1))))
})
