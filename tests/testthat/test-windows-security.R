test_that("Windows true symbolic links are readable and detached without deleting targets", {
  project = wsec_local()
  real = file.path(project, "real")
  dir.create(real)
  file = file.path(real, "sentinel.txt")
  writeLines("owned target survives", file)
  before = wsec_bytes(file)
  link = file.path(project, "dir-link")
  linked = wsec_link(real, link)
  expect_identical(wsec_bytes(file.path(link, "sentinel.txt")), before)
  expect_true(path_inside(link, project))
  expect_identical(path_key(link), path_key(real))
  alias = file.path(project, "file-link.txt")
  aliased = wsec_link(file, alias)
  expect_identical(path_key(alias), path_key(file))
  wsec_unlink(alias, FALSE, aliased$cleanup_script)
  wsec_unlink(link, TRUE, linked$cleanup_script)
  expect_true(file.exists(file))
  expect_identical(wsec_bytes(file), before)
})

test_that("Windows safe instruction links remain while escaped and guarded inputs stay private", {
  project = wsec_local()
  rules = file.path(project, "rules.md")
  writeLines("safe linked project instruction", rules)
  user = file.path(gptr_user_dir("config", create = TRUE), "AGENTS.md")
  writeLines("user-level instruction", user)
  link = file.path(project, "AGENTS.md")
  wsec_link(rules, link)
  expect_true(path_inside(link, project))
  expect_false(context_file_guarded(link, project))
  local_fake_provider(list("unused"))
  session = session_new("fake/fake-1", "manual", home = new.env(parent = emptyenv()))
  texts = function() {
    vapply(context_first_message(session, list(turn = 1L, human = FALSE)), function(x) x$text, "")
  }
  expect_true(any(grepl("safe linked project instruction", texts(), fixed = TRUE)))
  expect_true(any(grepl("user-level instruction", texts(), fixed = TRUE)))
  outside = withr::local_tempdir("gptr-wsec-foreign-")
  for (kind in c("outside", "guarded")) {
    target = if (kind == "outside") file.path(outside, "foreign.txt") else
      file.path(project, ".env")
    writeLines("PRIVATE_SYNTHETIC_WINDOWS_SENTINEL", target)
    before = wsec_preserve(target)
    blocked = file.path(project, if (kind == "outside") "CLAUDE.local.md" else
                          ".gptr/vignette.Rmd")
    wsec_link(target, blocked)
    expect_true(!path_inside(blocked, project) || context_file_guarded(blocked, project))
    expect_false(any(grepl("PRIVATE_SYNTHETIC_WINDOWS_SENTINEL", texts(), fixed = TRUE)))
    plan = context_instruction_items(list(mode = "plan", human = FALSE))
    expect_false(any(grepl("PRIVATE_SYNTHETIC_WINDOWS_SENTINEL",
                          vapply(plan, function(x) x$text, ""), fixed = TRUE)))
    expect_identical(wsec_bytes(target), before)
  }
})

test_that("Windows cache and checkpoint cleanup never follow foreign directory links", {
  project = wsec_local()
  root = file.path(project, ".gptr")
  outside = withr::local_tempdir("gptr-wsec-foreign-")
  foreign = file.path(outside, "foreign.gz")
  writeLines("foreign sentinel", foreign)
  Sys.setFileTime(foreign, Sys.time() - 40 * 86400)
  before = wsec_preserve(foreign)
  cache = file.path(root, "cache", "s1")
  dir.create(cache)
  wsec_link(outside, file.path(cache, "aa"))
  owned = file.path(cache, "owned.json")
  writeLines("{}", owned)
  expect_identical(gptr_cache("info", "s1")$entries[1L], 1L)
  expect_identical(gptr_cache("clear", "s1"), 1L)
  expect_false(file.exists(owned))
  expect_identical(wsec_bytes(foreign), before)
  blobs = file.path(root, "checkpoints", "blobs")
  dir.create(blobs, recursive = TRUE)
  wsec_link(outside, file.path(blobs, "ab"))
  owned = file.path(blobs, paste0(strrep("cd", 16L), ".gz"))
  writeLines("owned old blob", owned)
  Sys.setFileTime(owned, Sys.time() - 40 * 86400)
  expect_identical(ckpt_gc(root, days = 30)$deleted, 1L)
  expect_false(file.exists(owned))
  expect_identical(wsec_bytes(foreign), before)
  expect_false(file.exists(file.path(outside, "index.json")))
})

test_that("Windows scrub excludes escaping links and never writes through a foreign lock root", {
  project = wsec_local()
  outside = withr::local_tempdir("gptr-wsec-foreign-")
  late = "FAKE_windows_scrub_0123456789"
  foreign = file.path(outside, "foreign.txt")
  writeLines(late, foreign)
  before = wsec_preserve(foreign)
  cache = file.path(project, ".gptr", "cache")
  wsec_link(outside, file.path(cache, "escape"))
  wsec_link(foreign, file.path(cache, "escaped.txt"))
  secret_register(late, "WINDOWS_TEST_KEY", "test")
  expect_identical(nrow(gptr_scrub()), 0L)
  expect_identical(nrow(gptr_scrub(cache)), 0L)
  expect_identical(wsec_bytes(foreign), before)
  owned = file.path(project, "notes.txt")
  writeLines(late, owned)
  owned_before = wsec_bytes(owned)
  wsec_link(outside, file.path(project, ".gptr", "locks"))
  gptr_scrub(owned, dry_run = FALSE)
  expect_identical(wsec_bytes(owned), owned_before)
  expect_identical(wsec_bytes(foreign), before)
  expect_identical(list.files(outside, all.files = TRUE, no.. = TRUE), "foreign.txt")
})

test_that("Windows scrub refuses a dangling lock-root junction before taking any lock", {
  project = wsec_local()
  outside = withr::local_tempdir("gptr-wsec-foreign-")
  gone = file.path(outside, "gone")
  expect_true(dir.create(gone))
  lock_root = file.path(project, ".gptr", "locks")
  wsec_junction(gone, lock_root)
  expect_false(path_dangling(lock_root))
  expect_identical(unlink(gone, recursive = TRUE), 0L)
  expect_true(path_dangling(lock_root))
  late = "FAKE_windows_scrub_dangling_lock_0123456789"
  secret_register(late, "WINDOWS_TEST_KEY", "test")
  owned = file.path(project, "notes.txt")
  writeLines(late, owned)
  before = wsec_bytes(owned)
  # Taking a writer lock writes its pid file, even one released after a later failure.
  taken = character()
  atomic = write_atomic
  testthat::local_mocked_bindings(write_atomic = function(path, content) {
    taken <<- c(taken, path)
    atomic(path, content)
  })
  expect_null(scrub_lock(owned))
  gptr_scrub(owned, dry_run = FALSE)
  expect_identical(taken, character())
  expect_identical(wsec_bytes(owned), before)
  expect_false(dir.exists(paste0(owned, ".lock")))
  expect_identical(list.files(outside, all.files = TRUE, no.. = TRUE), character())
  # The junction helper's teardown oracle expects its target back.
  expect_true(dir.create(gone))
})

test_that("Windows checkpoint walks label links and forbid restoring through them", {
  project = wsec_local()
  data = file.path(project, "data")
  dir.create(data)
  source = file.path(data, "x.csv")
  writeLines("id\n1", source)
  before = wsec_bytes(source)
  link = file.path(project, "data-link")
  wsec_link(data, link)
  walked = ckpt_walk(project)
  expect_true("data-link" %in% walked$path)
  expect_true(walked$link[walked$path == "data-link"])
  expect_false("data-link/x.csv" %in% walked$path)
  guard = ckpt_restore_guard(file.path(link, "x.csv"))
  expect_false(guard$ok)
  expect_match(guard$reason, "symbolic link", fixed = TRUE)
  expect_identical(wsec_bytes(source), before)
})

test_that("Windows writes resolve links and edits refuse duplicate physical file operations", {
  project = wsec_local()
  real = file.path(project, "real.R")
  writeBin(charToRaw("x = 1\r\n"), real)
  alias = file.path(project, "alias.R")
  wsec_link(real, alias)
  written = write_file(alias, "x = 2\n")
  expect_identical(wsec_bytes(real), charToRaw("x = 2\r\n"))
  expect_identical(wsec_bytes(alias), wsec_bytes(real))
  expect_identical(path_key(written$details$path), path_key(real))
  expect_true(basename(alias) %in% list.files(project))
  before = wsec_bytes(real)
  patch = paste(c("*** Begin Patch", "*** Update File: alias.R", "@@", "-x = 2", "+x = 3",
                  "*** Update File: real.R", "@@", "-x = 2", "+x = 4", "*** End Patch"),
                collapse = "\n")
  expect_error(patch_apply(patch, root = project), "more than one operation names", fixed = TRUE,
               class = "gptr_error_invalid_argument")
  expect_identical(wsec_bytes(real), before)
  expect_identical(wsec_bytes(alias), before)
})

test_that("Windows settings refresh after a same-size rewrite with unchanged file timestamps", {
  wsec_local()
  path = settings_path("user", create = TRUE)
  writeLines('{"mode":"plan"}', path)
  wsec_mtime(path)
  # Windows ctime is creation time: age the real file before priming the two-second cache.
  Sys.sleep(2.1)
  expect_identical(settings_read("user")$mode, "plan")
  expect_false(is.null(get0(path, envir = gateway_state()$files, inherits = FALSE)))
  wsec_rewrite(path, '{"mode":"auto"}')
  expect_identical(settings_read("user")$mode, "auto")
})

test_that("Windows same-size gated rewrites revoke trust even with unchanged file timestamps", {
  project = wsec_local()
  path = file.path(project, ".gptr", "settings.json")
  writeLines('{"mode":"plan"}', path)
  wsec_mtime(path)
  gptr_trust(project, trust = TRUE)
  expect_true(trust_get(project))
  before = trust_fingerprint(project)$fp
  wsec_rewrite(path, '{"mode":"auto"}')
  expect_false(trust_get(project))
  expect_false(identical(trust_fingerprint(project)$fp, before))
})


test_that(
  "Windows known junctions are labelled and excluded from cache and checkpoint cleanup", {
  project = wsec_local()
  root = file.path(project, ".gptr")
  outside = withr::local_tempdir("gptr-wsec-junction-foreign-")
  foreign = file.path(outside, "foreign.json")
  blob = file.path(outside, "foreign.gz")
  writeBin(charToRaw("PUBLIC-JUNCTION-FOREIGN-JSON"), foreign)
  writeBin(charToRaw("PUBLIC-JUNCTION-FOREIGN-BLOB"), blob)
  old = Sys.time() - 40 * 86400
  expect_true(Sys.setFileTime(blob, old))
  before = wsec_preserve(foreign)
  blob_before = wsec_preserve(blob)
  link = file.path(project, "data-junction")
  linked = wsec_junction(outside, link)
  expect_identical(path_key(link), path_key(outside))
  expect_false(path_inside(link, project))
  expect_true(path_is_link(link))
  walked = ckpt_walk(project)
  expect_true("data-junction" %in% walked$path)
  expect_true(walked$link[walked$path == "data-junction"])
  expect_false(any(startsWith(walked$path, "data-junction/")))
  guard = ckpt_restore_guard(file.path(link, "foreign.json"))
  expect_false(guard$ok)
  expect_identical(guard$reason, "through a symbolic link")
  cache = file.path(root, "cache", "s1")
  expect_true(dir.create(cache))
  cached = wsec_junction(outside, file.path(cache, "aa"))
  owned = file.path(cache, "owned.json")
  writeBin(charToRaw("{}"), owned)
  expect_identical(gptr_cache("info", "s1")$entries[1L], 1L)
  expect_identical(gptr_cache("clear", "s1"), 1L)
  expect_false(file.exists(owned))
  blobs = file.path(root, "checkpoints", "blobs")
  expect_true(dir.create(blobs, recursive = TRUE))
  checkpoint = wsec_junction(outside, file.path(blobs, "ab"))
  owned = file.path(blobs, paste0(strrep("cd", 16L), ".gz"))
  writeBin(charToRaw("PUBLIC-JUNCTION-OWNED-BLOB"), owned)
  expect_true(Sys.setFileTime(owned, old))
  expect_identical(ckpt_gc(root, days = 30)$deleted, 1L)
  expect_false(file.exists(owned))
  expect_identical(wsec_bytes(foreign), before)
  expect_identical(wsec_bytes(blob), blob_before)
  expect_false(file.exists(file.path(outside, "index.json")))
  wsec_unlink(file.path(blobs, "ab"), TRUE, checkpoint$cleanup_script)
  wsec_unlink(file.path(cache, "aa"), TRUE, cached$cleanup_script)
  wsec_unlink(link, TRUE, linked$cleanup_script)
  expect_identical(wsec_bytes(foreign), before)
  expect_identical(wsec_bytes(blob), blob_before)
})
