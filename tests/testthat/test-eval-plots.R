test_that("plot_png keeps no PNG file and keeps the current device, also when replay fails", {
  skip_if_not(isTRUE(capabilities("png")) || requireNamespace("ragg", quietly = TRUE))
  p = record_scatter()
  tmp = dirname(ws_path("cache", "tmp", "gptr-plot-probe"))
  pngs = function() list.files(tmp, pattern = "^gptr-plot-.*[.]png$")
  before = pngs()
  grDevices::pdf(NULL)
  u1 = grDevices::dev.cur()
  grDevices::pdf(NULL)
  u2 = grDevices::dev.cur()
  withr::defer(grDevices::dev.off(u2))
  withr::defer(grDevices::dev.off(u1))
  grDevices::dev.set(u1)
  expect_match(plot_png(p)$data, "^iVBORw0KGgo")
  expect_equal(grDevices::dev.cur(), u1)
  expect_error(plot_png(structure(list(), class = "recordedplot")))
  expect_equal(grDevices::dev.cur(), u1)
  expect_identical(pngs(), before)
})

test_that("in capture mode, a device opened at the number of a closed user device is captured", {
  dir = withr::local_tempdir()
  withr::local_dir(dir)
  devs = grDevices::dev.list()
  old = getOption("device")
  grDevices::pdf(NULL)
  user_dev = grDevices::dev.cur()
  withr::defer(if (user_dev %in% grDevices::dev.list()) grDevices::dev.off(user_dev))
  ps = plot_begin("capture", human = FALSE)
  withr::defer(plot_close(ps))
  expect_false(ps$our_dev == user_dev)
  graphics::plot(1:3)
  expect_true(plot_capture(ps, incomplete = TRUE))
  grDevices::dev.off(user_dev)
  grDevices::dev.off(ps$our_dev)
  graphics::plot(3:1)
  expect_equal(grDevices::dev.cur(), user_dev)
  expect_true(plot_capture(ps, incomplete = TRUE))
  expect_equal(ps$n, 2L)
  plot_close(ps)
  expect_identical(getOption("device"), old)
  expect_identical(grDevices::dev.list(), devs)
  expect_false(file.exists(file.path(dir, "Rplots.pdf")))
})

test_that("plot_render_all removes the PNG of a failed replay and gives NA for it", {
  skip_if_not(isTRUE(capabilities("png")) || requireNamespace("ragg", quietly = TRUE))
  tmp = dirname(ws_path("cache", "tmp", "gptr-plot-probe"))
  pngs = function() list.files(tmp, pattern = "^gptr-plot-.*[.]png$")
  before = pngs()
  ps = plot_begin("capture", human = FALSE)
  withr::defer(plot_close(ps))
  graphics::plot(1:3)
  expect_true(plot_capture(ps, incomplete = TRUE))
  ps$recorded[[2L]] = structure(list(), class = "recordedplot")
  ps$n = 2L
  plot_close(ps)
  files = plot_render_all(ps)
  withr::defer(unlink(files[!is.na(files)]))
  expect_length(files, 2L)
  expect_false(is.na(files[[1L]]))
  expect_true(file.exists(files[[1L]]))
  expect_true(is.na(files[[2L]]))
  expect_identical(setdiff(pngs(), before), basename(files[[1L]]))
})
