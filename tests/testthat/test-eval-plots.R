test_that("low-level additions update the captured page instead of adding a plot", {
  ps = plot_begin("capture", human = FALSE)
  withr::defer(plot_close(ps))
  graphics::plot(1:10)
  expect_true(plot_capture(ps))
  graphics::abline(h = 5)
  expect_false(plot_capture(ps, incomplete = TRUE))
  expect_equal(ps$n, 1L)
  expect_length(ps$recorded[[1L]][[1L]], length(grDevices::recordPlot()[[1L]]))
  graphics::plot(3:1)
  expect_true(plot_capture(ps, incomplete = TRUE))
  expect_equal(ps$n, 2L)
})

test_that("a device the code opens after closing the offscreen one is offscreen too (IC-67)", {
  dir = withr::local_tempdir()
  withr::local_dir(dir)
  devs = grDevices::dev.list()
  old = getOption("device")
  ps = plot_begin("auto", human = FALSE)
  withr::defer(plot_close(ps))
  graphics::plot(1:3)
  expect_true(plot_capture(ps, incomplete = TRUE))
  grDevices::dev.off()
  graphics::plot(1:3)
  graphics::abline(h = 2)
  expect_true(plot_capture(ps, incomplete = TRUE))
  grDevices::dev.off()
  graphics::par(mfrow = c(1L, 2L))
  graphics::plot(3:1)
  graphics::plot(1:3)
  expect_true(plot_capture(ps, incomplete = TRUE))
  grDevices::dev.off()
  grid::grid.rect()
  expect_true(plot_capture(ps, incomplete = TRUE))
  plot_close(ps)
  expect_identical(getOption("device"), old)
  expect_identical(grDevices::dev.list(), devs)
  expect_equal(ps$n, 4L)
  expect_length(ps$last_dl, 0L)
  expect_false(file.exists(file.path(dir, "Rplots.pdf")))
})

