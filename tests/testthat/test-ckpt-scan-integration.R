# Real children, real filesystem changes and the public fake-provider Peter flow.
scan_integration_library = function(.env = parent.frame()) {
  path = getNamespaceInfo(asNamespace("gptr"), "path")
  if (file.exists(file.path(path, "R", "aaa-state.R"))) local_worker_lib(.env)
}

scan_integration_bytes = function(path) readBin(path, "raw", file.size(path))

test_that("real partial checkpoints preserve targeted writes and report native coverage honestly", {
  skip_on_cran()
  scan_integration_library()
  root = local_project(files = list("a-known.R" = "known = 1", "b-delete.R" = "delete = 1",
    "zz-target/deep/target.R" = "before", "zz-target/deep/preexisting.txt" = "keep me"))
  local_gptr_options(checkpoint_scan_timeout = 20, checkpoint_scan_budget = 1000, quiet = TRUE)
  for (part in c("one", "two")) {
    dir = file.path(root, "bulk", part)
    expect_true(dir.create(dir, recursive = TRUE))
    expect_true(all(file.create(file.path(dir, sprintf("f%04d.bin", seq_len(1100L))))))
  }
  target_rel = "zz-target/deep/target.R"
  target = file.path(root, target_rel)
  original = scan_integration_bytes(target)
  edited = charToRaw("after\nchanged line\n")
  local_fake_provider(list("ready", fake_tool("write", path = target_rel,
                                             content = rawToChar(edited)), "done"))
  session = peter("ready", model = "fake/fake-1", mode = "auto", envir = new.env())
  session_ck = ckpt_ck_of(ckpt_ext_state(session), session)
  session_tr = ckpt_files_tr(session_ck)
  ckpt_files_sync(session_tr)
  expect_false(session_tr$complete)
  expect_length(session_tr$hash, 256L)
  expect_false(target_rel %in% session_tr$stat$path)
  expect_false(target_rel %in% names(session_tr$hash))

  session |> peter("replace the requested file")
  expect_identical(scan_integration_bytes(target), edited)
  edited_leaf = session_data(session)$leaf
  preview = gptr_rewind(session, 1, preview = TRUE)
  expect_true("file coverage" %in% preview$item)
  expect_false(preview$restore[match("file coverage", preview$item)])
  expect_warning(gptr_rewind(session, 1), class = "gptr_warning_rewind_partial")
  expect_identical(scan_integration_bytes(target), original)
  expect_true(session$last_rewind$partial)
  expect_true(any(startsWith(session$last_rewind$report, "file coverage: not restored")))
  expect_warning(gptr_rewind(session, to = edited_leaf), class = "gptr_warning_rewind_partial")
  expect_identical(scan_integration_bytes(target), edited)
  writeBin(original, target)

  ck = ckpt_ck_new("s0000000901")
  tr = ckpt_files_tr(ck)
  ckpt_files_sync(tr)
  expect_false(tr$complete)
  expect_true(all(c("a-known.R", "b-delete.R") %in% names(tr$hash)))
  unknown_rel = "zz-target/deep/preexisting.txt"
  unknown = file.path(root, unknown_rel)
  expect_false(unknown_rel %in% tr$stat$path)
  coverage_only = ckpt_files_turn_scan(ck, 1L, force = TRUE)
  expect_length(coverage_only$files, 0L)
  expect_identical(coverage_only$coverage, "partial")
  coverage_report = ckpt_files_undo(ck, coverage_only)
  expect_identical(coverage_report$item, "file coverage")
  expect_false(coverage_report$ok)
  expect_match(coverage_report$action, "unobserved file changes may remain", fixed = TRUE)

  # The CLI may have written an unknown file before serving a gptr tool request.
  writeLines("native unknown change", unknown)
  call = list(id = "native-late-target", name = "write",
              input = list(path = unknown_rel, content = "served write"))
  token = ckpt_files_before(ck, call, turn = 1L, sync = FALSE)
  expect_false(token$exact)
  writeLines("served write", unknown)
  unknown_after = scan_integration_bytes(unknown)
  late = ckpt_files_after(ck, call, token)
  expect_length(late$files, 0L)
  expect_identical(late$coverage, "partial")
  expect_false(ckpt_files_undo(ck, late)$ok)
  expect_identical(scan_integration_bytes(unknown), unknown_after)

  known = file.path(root, "a-known.R")
  deleted = file.path(root, "b-delete.R")
  known_before = scan_integration_bytes(known)
  deleted_before = scan_integration_bytes(deleted)
  writeLines("native change", known)
  known_after = scan_integration_bytes(known)
  expect_true(file.remove(deleted))
  native = ckpt_files_turn_scan(ck, 2L, force = TRUE)
  statuses = stats::setNames(vapply(native$files, function(row) row$status, ""),
                             vapply(native$files, function(row) row$path, ""))
  expect_identical(statuses[["a-known.R"]], "modified")
  expect_identical(statuses[["b-delete.R"]], "deleted")
  expect_false(unknown_rel %in% names(statuses))
  expect_identical(native$coverage, "partial")
  undone = ckpt_files_undo(ck, native)
  expect_true(all(undone$ok[undone$item != "file coverage"]))
  expect_false(undone$ok[undone$item == "file coverage"])
  expect_identical(scan_integration_bytes(known), known_before)
  expect_identical(scan_integration_bytes(deleted), deleted_before)
  redone = ckpt_files_undo(ck, native, redo = TRUE)
  expect_true(all(redone$ok[redone$item != "file coverage"]))
  expect_identical(scan_integration_bytes(known), known_after)
  expect_false(file.exists(deleted))
  expect_identical(scan_integration_bytes(unknown), unknown_after)

  # Removing only disposable fixture bulk permits a later complete inventory.
  unlink(file.path(root, "bulk"), recursive = TRUE)
  transition = ckpt_files_scan(tr)
  expect_true(transition$complete)
  expect_true(unknown_rel %in% transition$walk$path)
  expect_false(unknown_rel %in% transition$created)
  ckpt_files_sync(tr)
  expect_true(tr$complete)
  expect_true(tr$coverage)
  expect_null(ckpt_files_turn_scan(ck, 3L, force = TRUE))
  expect_identical(scan_integration_bytes(unknown), unknown_after)
})

test_that("real complete scans detect same-size edits with an unchanged timestamp", {
  scan_integration_library()
  root = local_project(files = list("racy.R" = "AAAA"))
  local_gptr_options(checkpoint_scan_timeout = 15, checkpoint_scan_budget = 1000)
  path = file.path(root, "racy.R")
  stamp = as.POSIXct(1e9, origin = "1970-01-01", tz = "UTC")
  expect_true(Sys.setFileTime(path, stamp))
  ck = ckpt_ck_new("s0000000902")
  tr = ckpt_files_tr(ck)
  ckpt_files_sync(tr)
  expect_true(tr$complete)
  before = scan_integration_bytes(path)
  before_info = file.info(path)
  writeBin(charToRaw("BBBB\n"), path)
  expect_true(Sys.setFileTime(path, stamp))
  expect_identical(file.size(path), before_info$size)
  expect_identical(as.numeric(file.mtime(path)), as.numeric(before_info$mtime))
  after = scan_integration_bytes(path)
  fragment = ckpt_files_turn_scan(ck, 1L, force = TRUE)
  expect_identical(fragment$coverage, "complete")
  expect_length(fragment$files, 1L)
  expect_identical(fragment$files[[1L]]$status, "modified")
  expect_true(ckpt_files_undo(ck, fragment)$ok)
  expect_identical(scan_integration_bytes(path), before)
  expect_true(ckpt_files_undo(ck, fragment, redo = TRUE)$ok)
  expect_identical(scan_integration_bytes(path), after)
})

test_that("real scans retain old files behind a replaced directory link without reading outside", {
  skip_on_os("windows")
  scan_integration_library()
  root = local_project(files = list("inside/known.R" = "original"))
  local_gptr_options(checkpoint_scan_timeout = 15, checkpoint_scan_budget = 1000)
  outside = withr::local_tempdir()
  outside_file = file.path(outside, "known.R")
  writeLines("synthetic outside content", outside_file)
  outside_bytes = scan_integration_bytes(outside_file)
  outside_hash = hash_file(outside_file)
  ck = ckpt_ck_new("s0000000903")
  tr = ckpt_files_tr(ck)
  ckpt_files_sync(tr)
  original_hash = tr$hash[["inside/known.R"]]
  expect_true(tr$complete)
  unlink(file.path(root, "inside"), recursive = TRUE)
  skip_if_not(file.symlink(outside, file.path(root, "inside")), "directory links unavailable")
  fragment = ckpt_files_turn_scan(ck, 1L, force = TRUE)
  expect_identical(fragment$coverage, "partial")
  expect_true("inside/known.R" %in% tr$stat$path)
  expect_identical(tr$hash[["inside/known.R"]], original_hash)
  expect_false(any(vapply(fragment$files, function(row) {
    identical(row$path, "inside/known.R") && identical(row$status, "deleted")
  }, logical(1))))
  expect_null(ckpt_blob_find(outside_hash))
  report = ckpt_files_undo(ck, fragment)
  expect_true(any(!report$ok))
  expect_identical(scan_integration_bytes(outside_file), outside_bytes)
  expect_true(dir.exists(file.path(root, "inside")))
})

test_that("a real unreadable baseline stays partial until readable contents are backed up", {
  skip_on_os("windows")
  scan_integration_library()
  root = local_project(files = list("permission.R" = "AAAA"))
  local_gptr_options(checkpoint_scan_timeout = 15, checkpoint_scan_budget = 1000, quiet = TRUE)
  path = file.path(root, "permission.R")
  stamp = as.POSIXct(1e9, origin = "1970-01-01", tz = "UTC")
  expect_true(Sys.setFileTime(path, stamp))
  original_hash = hash_file(path)
  before_info = file.info(path)
  withr::defer(Sys.chmod(path, "0600", use_umask = FALSE))
  expect_true(Sys.chmod(path, "0000", use_umask = FALSE))
  skip_if(file.access(path, 4L) == 0L, "permissions do not prevent this user from reading")
  ck = ckpt_ck_new("s0000000904")
  tr = ckpt_files_tr(ck)
  ckpt_files_sync(tr)
  expect_true(tr$complete)
  expect_false(tr$coverage)
  expect_identical(tr$stat$path, "permission.R")
  expect_length(tr$hash, 0L)
  expect_null(ckpt_blob_find(original_hash))

  expect_true(Sys.chmod(path, "0600", use_umask = FALSE))
  native_bytes = charToRaw("BBBB\n")
  writeBin(native_bytes, path)
  expect_true(Sys.setFileTime(path, stamp))
  expect_identical(file.size(path), before_info$size)
  expect_identical(as.numeric(file.mtime(path)), as.numeric(before_info$mtime))
  fragment = ckpt_files_turn_scan(ck, 1L, force = TRUE)
  expect_length(fragment$files, 0L)
  expect_identical(fragment$coverage, "partial")
  report = ckpt_files_undo(ck, fragment)
  expect_identical(report$item, "file coverage")
  expect_false(report$ok)
  expect_identical(scan_integration_bytes(path), native_bytes)
  expect_null(ckpt_blob_find(original_hash))

  expect_true(tr$complete)
  expect_true(tr$coverage)
  expect_identical(tr$hash[["permission.R"]], hash_file(path))
  expect_null(ckpt_files_turn_scan(ck, 2L, force = TRUE))
  later_bytes = charToRaw("CCCC\n")
  writeBin(later_bytes, path)
  expect_true(Sys.setFileTime(path, stamp))
  later = ckpt_files_turn_scan(ck, 3L, force = TRUE)
  expect_identical(later$coverage, "complete")
  expect_length(later$files, 1L)
  expect_identical(later$files[[1L]]$status, "modified")
  expect_true(ckpt_files_undo(ck, later)$ok)
  expect_identical(scan_integration_bytes(path), native_bytes)
  expect_true(ckpt_files_undo(ck, later, redo = TRUE)$ok)
  expect_identical(scan_integration_bytes(path), later_bytes)
})
