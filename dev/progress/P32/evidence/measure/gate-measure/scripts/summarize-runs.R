# Medians of wall/outer/internal/gap by tag and variant over runs-*.csv files (warm-up rows kept apart)
args = commandArgs(TRUE)
d = do.call(rbind, lapply(args, read.csv, stringsAsFactors = FALSE))
d$variant = ifelse(d$variant == "warm", paste0("warm", d$rep), d$variant)
num = c("wall_s", "outer_s", "internal_s", "gap_s")
m = aggregate(d[num], list(tag = d$tag, variant = d$variant), median)
n = aggregate(list(reps = d$rep), list(tag = d$tag, variant = d$variant), length)
e = aggregate(list(errors = d$is_error), list(tag = d$tag, variant = d$variant), function(x) sum(x %in% TRUE))
m = merge(merge(m, n), e)
print(m[order(m$tag, m$variant), ], row.names = FALSE, digits = 3)
